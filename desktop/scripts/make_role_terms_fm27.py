#!/usr/bin/env python3
"""Generate src/core/RoleTermsData.cpp from data/fm27/glossary-fm27.csv.

The app shows FM27 role names and abbreviations in the UI language, with the
game's own wording for that language. The glossary holds those terms; this
script turns its "role" and "role_abbr" rows into a lookup table:
language -> role id -> (English name, name, abbreviation). Role ids are the
English abbreviations, with "-IP"/"-OOP" where an abbreviation exists in both
phases ("CB-IP", "IF"), as in definitions_fm27.json.

Run after every glossary change:
    python3 desktop/scripts/make_role_terms_fm27.py
"""
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
GLOSSARY = ROOT / "data" / "fm27" / "glossary-fm27.csv"
CPP_OUT = ROOT / "src" / "core" / "RoleTermsData.cpp"
LANGS = ["de", "fr", "it", "zh_CN", "ru", "es"]


def cpp_string(text):
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    if all(ord(c) < 128 for c in text):
        return f'QStringLiteral("{escaped}")'
    return f'QString::fromUtf8("{escaped}")'


def main():
    with open(GLOSSARY, encoding="utf-8-sig") as handle:
        rows = list(csv.DictReader(handle, delimiter=";"))
    names = {r["id"]: r for r in rows if r["category"] == "role"}
    terms = {lang: [] for lang in LANGS}
    phases = {}
    for row in rows:
        if row["category"] == "role_abbr":
            _, phase, abbr = row["id"].split(".", 2)
            phases.setdefault(abbr, set()).add(phase)
    for row in rows:
        if row["category"] != "role_abbr":
            continue
        _, phase, abbr = row["id"].split(".", 2)
        # The note starts with the English role name.
        english = row["note"].split(";")[0].strip()
        name_row = names.get(f"role.{phase}.{english}")
        if name_row is None:
            raise SystemExit(f"no role row for {row['id']} ({english})")
        role_id = f"{abbr}-{phase.upper()}" if len(phases[abbr]) > 1 else abbr
        for lang in LANGS:
            if name_row[lang] and row[lang]:
                terms[lang].append((role_id, english, name_row[lang].strip(),
                                    row[lang].strip()))
    lines = [
        "// Generated by desktop/scripts/make_role_terms_fm27.py - do not edit by hand.",
        "// FM27 role names and abbreviations in each UI language, as the game words them",
        "// (from data/fm27/glossary-fm27.csv).",
        "",
        '#include "RoleTermsData.h"',
        "",
        "namespace fm {",
        "",
        "const QHash<QString, QHash<QString, RoleTerm>> &fm27RoleTerms()",
        "{",
        "    static const QHash<QString, QHash<QString, RoleTerm>> terms = [] {",
        "        QHash<QString, QHash<QString, RoleTerm>> all;",
    ]
    for lang in LANGS:
        lines.append("        {")
        lines.append(f"            auto &t = all[QStringLiteral(\"{lang}\")];")
        for key, english, name, abbr in sorted(terms[lang]):
            lines.append(f"            t.insert({cpp_string(key)}, {{{cpp_string(english)}, "
                         f"{cpp_string(name)}, {cpp_string(abbr)}}});")
        lines.append("        }")
    lines += ["        return all;", "    }();", "    return terms;", "}", "",
              "} // namespace fm", ""]
    CPP_OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{sum(len(v) for v in terms.values())} role terms -> {CPP_OUT}")


if __name__ == "__main__":
    main()
